/** URLの ?lang= ＞ 保存済みの選択 ＞ ブラウザの言語（日本語以外は英語）の順で決める。 */
export function detectLang({ search = "", stored = null, navLang = "" } = {}) {
  let q = null;
  try { q = new URLSearchParams(search).get("lang"); } catch { /* 不正なら無視 */ }
  if (LANGS.includes(q)) return q;
  if (LANGS.includes(stored)) return stored;
  return /^ja/i.test(String(navLang || "")) ? "ja" : "en";
}

/** 文言を引く。{name} 形式の置換に対応。未定義の言語・キーは日本語→キー名の順にフォールバック。 */
export function t(lang, key, params = {}) {
  const table = DICT[lang] || DICT.ja;
  let s = table[key];
  if (s === undefined) s = DICT.ja[key];
  if (s === undefined) return key;
  if (typeof s !== "string") return s; // notes など配列
  return s.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? String(params[k]) : m));
}

/** 順位の表記（日本語: 9位 / 英語: 9th）。 */
export function placeLabel(lang, n) {
  if (lang !== "en") return `${n}位`;
  const v = n % 100;
  if (v >= 11 && v <= 13) return `${n}th`;
  return `${n}${({ 1: "st", 2: "nd", 3: "rd" })[n % 10] || "th"}`;
}

/** テスト用: 両言語のキーが揃っているかの確認に使う。 */
export function dictKeys(lang) {
  return Object.keys(DICT[lang] || {});
}
